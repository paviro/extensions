"""Render moon.h, the moon of the Now Playing timer: Cupertino Icons moon_fill
fitted into an 11 x 11 coverage mask, one byte per pixel. Drawing uses
ImageMagick's `magick`; the font (CupertinoIcons.ttf from the Flutter
`cupertino_icons` package, MIT, see LICENSE.cupertino-icons) is not in the
repository.

    python3 assets/render.py --font CupertinoIcons.ttf
    python3 assets/render.py --font CupertinoIcons.ttf --check
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "moon.h"
SIZE = 11
MOON_FILL = 0xF719


def render(font):
    pixels = subprocess.run(
        [
            "magick",
            "-background",
            "black",
            "-fill",
            "white",
            "-font",
            font,
            "-pointsize",
            "400",
            f"label:{chr(MOON_FILL)}",
            "-trim",
            "+repage",
            "-resize",
            f"{SIZE}x{SIZE}",
            "-gravity",
            "Center",
            "-extent",
            f"{SIZE}x{SIZE}",
            "-colorspace",
            "gray",
            "-depth",
            "8",
            "gray:-",
        ],
        check=True,
        capture_output=True,
    ).stdout
    if len(pixels) != SIZE * SIZE:
        sys.exit(f"magick returned {len(pixels)} bytes, not {SIZE * SIZE}")
    rows = "\n".join(
        "    " + ", ".join(f"{p:3d}" for p in pixels[y * SIZE : (y + 1) * SIZE]) + ","
        for y in range(SIZE)
    )
    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n\n"
        "/* Generated by assets/render.py from Cupertino Icons moon_fill (MIT, see\n"
        " * assets/LICENSE.cupertino-icons). */\n\n"
        f"#define MOON_SIZE {SIZE}\n\n"
        "/* clang-format off */\n"
        f"static const unsigned char moon[MOON_SIZE * MOON_SIZE] = {{\n{rows}\n}};\n"
        "/* clang-format on */\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--font", default=os.environ.get("CUPERTINO_ICONS"), help="CupertinoIcons.ttf"
    )
    parser.add_argument("--check", action="store_true", help="fail when moon.h differs")
    args = parser.parse_args()
    if not args.font:
        sys.exit("give the font with --font or CUPERTINO_ICONS")
    text = render(args.font)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.name} is out of date: run {Path(__file__).name}")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
